# ========== 2. 食品开销重分类 ==========
FOOD_RULES = [
    # (date, counter关键词, 新cat1, 新cat2, 说明)
    ("2026-08-16", "父亲", "食品烟酒", "伙食买菜(父亲经手)", "微信打给爸的6000买菜钱"),
    ("2026-08-30", "微信转账", "食品烟酒", "食材(阿姨代买)", "阿姨D阿姨·宝宝辅食食材预付500"),
    ("2026-09-01", "微信转账", "食品烟酒", "食材(阿姨代买)", "梁阿姨·奖金300"),
    ("2026-08-17", "岳父", "食品烟酒", "食材(岳父代买)", "打给岳父的5000"),
]
n_food = 0
for r in recs:
    for d, kw, c1, c2, note in FOOD_RULES:
        if r['date'] == d and kw in str(r['counter']):
            r['cat1'], r['cat2'] = c1, c2
            r['catGB'] = [c1, c2]
            r['catQS'] = ['食品酒水', c2]
            r['catZFB'] = ['餐饮美食', c2]
            r['note'] = (str(r.get('note','')) + '|' + note)[:40]
            n_food += 1

# ========== 3. 婴儿用品类 ============
BABY_KW = ['奶粉','尿布','尿裤','玩具','婴儿','贝亲','babycare','好孩子','爱他美','飞鹤','君乐宝',
           '尤妮佳','花王','好奇','帮宝适','童装','巴拉巴拉','英氏','戴维贝拉','棉柔巾','贝肽',
           '辅食','磨牙','安抚','摇铃','爬行垫','围栏','餐椅','安全座椅','婴儿床','推车','抱被',
           '连体','哈衣','口水巾','逸乐途','班迪','竹山','米妮','可爱','纽贝','佳尔','bu**店',
           'ko**店','ys**店','云**','天**','义乌','ysxx','竹山**']
def is_baby(r):
    s = str(r['counter']) + str(r.get('note',''))
    slow = str(r['counter']).lower() + str(r.get('note','')).lower()
    for kw in BABY_KW:
        if kw in s or kw in slow: return True
    return False

n_baby = 0
for r in recs:
    if r['cat1'] in ('医疗保健','教育文化娱乐') and r['cat2'] in ('宝宝医疗','宝宝早教','母婴护理'):
        continue  # 医疗/早教保留原类
    if r['cat1'] in ('其他用品及服务','生活用品及服务') and is_baby(r) and r['amt'] > 0:
        r['cat1'], r['cat2'] = '婴儿用品', '奶粉尿布玩具衣服'
        r['catGB'] = ['婴儿用品', '用品(奶粉/尿布/玩具/衣)']
        r['catQS'] = ['日常用品', '婴儿用品']
        r['catZFB'] = ['购物消费', '婴儿用品']
        n_baby += 1

